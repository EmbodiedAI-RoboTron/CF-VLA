T_co = TypeVar("T_co", covariant=True)


def sample_points_between(st: int, ed: int, n: int) -> List[int]:
    """
    Sample N points between st and ed, including both endpoints.
    If N > ed - st, pad with the last point (ed).
    
    Args:
        st: start index (int)
        ed: end index (int)
        n: number of points to sample (must be >= 2)
    
    Returns:
        list of N integers; first is st and last is ed
    
    Examples:
        >>> sample_points_between(0, 10, 5)
        [0, 2, 5, 7, 10]
        >>> sample_points_between(0, 10, 2)
        [0, 10]
        >>> sample_points_between(0, 5, 10)
        [0, 1, 2, 3, 4, 5, 5, 5, 5, 5]
    """
    if n < 2:
        raise ValueError(f"n must be >= 2 to include both st and ed, got {n}")
    if st > ed:
        raise ValueError(f"st ({st}) must be <= ed ({ed})")
    
    if n == 2:
        return [st, ed]
    
    # compute number of available integer points
    available_points = ed - st + 1
    
    if n > available_points:
        # if requested points exceed available points, use all points then pad with ed
        points = list(range(st, ed + 1))  # [st, st+1, ..., ed]
        # pad with ed until n points
        points.extend([ed] * (n - available_points))
        return points
    
    # use numpy linspace for uniform sampling then cast to int
    points = np.linspace(st, ed, n, dtype=int)
    # ensure first and last points are st and ed
    points[0] = st
    points[-1] = ed
    return points.tolist()


class Dataset(Protocol[T_co]):
    """Interface for a dataset with random access."""

    def __getitem__(self, index: SupportsIndex) -> T_co:
        raise NotImplementedError("Subclasses of Dataset should implement __getitem__.")

    def __len__(self) -> int:
        raise NotImplementedError("Subclasses of Dataset should implement __len__.")


class IterableDataset(Protocol[T_co]):
    """Interface for an iterable dataset."""

    def __iter__(self) -> Iterator[T_co]:
        raise NotImplementedError("Subclasses of IterableDataset should implement __iter__.")

    def __len__(self) -> int:
        raise NotImplementedError("Subclasses of Dataset should implement __len__.")


class DataLoader(Protocol[T_co]):
    """Interface for a data loader."""

    def data_config(self) -> _config.DataConfig:
        """Get the data config for this data loader."""
        raise NotImplementedError("Subclasses of DataLoader should implement data_config.")

    def __iter__(self) -> Iterator[T_co]:
        raise NotImplementedError("Subclasses of DataLoader should implement __iter__.")


class TransformedDataset(Dataset[T_co]):
    def __init__(self, dataset: Dataset, transforms: Sequence[_transforms.DataTransformFn]):
        self._dataset = dataset
        self._transform = _transforms.compose(transforms)

    def __getitem__(self, index: SupportsIndex) -> T_co:
        # index = index % 1
        return self._transform(self._dataset[index])

    def __len__(self) -> int:
        return len(self._dataset)


class IterableTransformedDataset(IterableDataset[T_co]):
    def __init__(
        self,
        dataset: IterableDataset,
        transforms: Sequence[_transforms.DataTransformFn],
        *,
        is_batched: bool = False,
    ):
        self._dataset = dataset
        self._transform = _transforms.compose(transforms)
        self._is_batched = is_batched

    def __iter__(self):
        for sample in self._dataset:
            if self._is_batched:
                # Transforms are designed to be applied to individual samples. So we need to split the batch into
                # individual samples and apply the transform to each sample individually.
                batch_size = next(v.shape[0] for v in sample.values())

                # Split batch into individual samples using tree_map
                individual_samples = [jax.tree.map(lambda x: x[i], sample) for i in range(batch_size)]  # noqa: B023

                # Transform each sample
                transformed = [self._transform(s) for s in individual_samples]

                # Recombine batch with tree_map
                yield jax.tree.map(lambda *x: np.stack(x, axis=0), *transformed)
            else:
                yield self._transform(sample)

    def __len__(self) -> int:
        return len(self._dataset)


class FakeDataset(Dataset):
    def __init__(self, model_config: _model.BaseModelConfig, num_samples: int):
        self._num_samples = num_samples
        self._observation_spec, self._action_spec = model_config.inputs_spec()

    def __getitem__(self, index: SupportsIndex) -> dict:
        rng = jax.random.key(index.__index__())

        def make_from_spec(spec: jax.ShapeDtypeStruct):
            nonlocal rng
            rng, data_rng = jax.random.split(rng)
            # Remove the batch dimension.
            shape = spec.shape[1:]
            if spec.dtype == jnp.float32:
                return jax.random.uniform(data_rng, shape=shape, minval=-1.0, maxval=1.0)
            if spec.dtype == jnp.int32:
                return jax.random.randint(data_rng, shape=shape, minval=0, maxval=2048)
            return jnp.zeros(shape=shape, dtype=spec.dtype)

        observation = jax.tree.map(make_from_spec, self._observation_spec)
        action = jax.tree.map(make_from_spec, self._action_spec)

        return {
            **observation.to_dict(),
            "actions": action,
        }

    def __len__(self) -> int:
        return self._num_samples


class LeRobotDataset(lerobot_dataset.LeRobotDataset):
    def __init__(self, repo_id: str, model_config: _model.BaseModelConfig, *args, **kwargs):
        super().__init__(repo_id, *args, **kwargs)
        self.model_config = model_config

    def _get_query_indices(self, idx: int, ep_idx: int) -> tuple[dict[str, list[int | bool]]]:
        ep_start = self.episode_data_index["from"][ep_idx]
        ep_end = self.episode_data_index["to"][ep_idx]
        query_indices = {
            key: [max(ep_start.item(), min(ep_end.item() - 1, idx + delta)) for delta in delta_idx]
            for key, delta_idx in self.delta_indices.items()
        }
        padding = {  # Pad values outside of current episode range
            f"{key}_is_pad": torch.BoolTensor(
                [(idx + delta < ep_start.item()) | (idx + delta >= ep_end.item()) for delta in delta_idx]
            )
            for key, delta_idx in self.delta_indices.items()
        }
        den = (ep_end.item() - ep_start.item())
        padding.update({
            f"{key}_status_bar": torch.Tensor(
                [(delta-ep_start.item()+1) / den for delta in delta_idx]
            )
            for key, delta_idx in query_indices.items()
        })
        return query_indices, padding

    def __getitem__(self, idx) -> dict:
        item = self.hf_dataset[idx]
        ep_idx = item["episode_index"].item()

        query_indices = None
        if self.delta_indices is not None:
            query_indices, padding = self._get_query_indices(idx, ep_idx)
            query_result = self._query_hf_dataset(query_indices)
            item = {**item, **padding}
            for key, val in query_result.items():
                item[key] = val

        if len(self.meta.video_keys) > 0:
            current_ts = item["timestamp"].item()
            query_timestamps = self._get_query_timestamps(current_ts, query_indices)
            video_frames = self._query_videos(query_timestamps, ep_idx)
            item = {**video_frames, **item}

        if self.image_transforms is not None:
            image_keys = self.meta.camera_keys
            for cam in image_keys:
                item[cam] = self.image_transforms(item[cam])

        # Add task as a string
        task_idx = item["task_index"].item()
        item["task"] = self.meta.tasks[task_idx]

        if self.model_config.model_kwargs.get("get_indices", False):
            ep_start = self.episode_data_index["from"][ep_idx]
            ep_end = self.episode_data_index["to"][ep_idx]
            item.update({
                f"indices": [idx, ep_start.item(), ep_end.item(), item['extra_data'].item()]
            })
        if self.model_config.model_kwargs.get("use_ref", False):
            traj_as_ref_length = self.model_config.model_kwargs.get("traj_as_ref_length", 50)
            ref_type = self.model_config.model_kwargs.get("ref_type", "goals")
            ep_start = self.episode_data_index["from"][ep_idx].item()
            ep_end = self.episode_data_index["to"][ep_idx].item() if self.model_config.model_kwargs.get("use_traj_full", False) else min(idx+traj_as_ref_length, self.episode_data_index["to"][ep_idx].item())
            assert ep_start <= idx <= ep_end-1, f"idx {idx} is out of range [{ep_start}, {ep_end-1}]"
            ref_indices = sample_points_between(idx, ep_end-1, traj_as_ref_length)
            query_result = self._query_hf_dataset({ref_type: ref_indices})
            item.update({
                f"ref": query_result[ref_type]
            })

        return item


class MultiLeRobotDataset(torch.utils.data.Dataset):
    def __init__(self, data_config: _config.DataConfig, action_horizon: int, model_config: _model.BaseModelConfig):
        self._datasets = []
        repo_ids = [data_config.repo_id]
        if data_config.multi_repos is not None:
            repo_ids = data_config.multi_repos["repo_ids"]
        
        for repo_id in repo_ids:
            dataset_meta = lerobot_dataset.LeRobotDatasetMetadata(repo_id)  # load dataset metadata from repo_id path, e.g., task and episode counts
            delta_timestamps = {key: [t / dataset_meta.fps for t in range(action_horizon)] for key in data_config.action_sequence_keys}
            if data_config.hist_objs_config is not None:
                for obj_key, obj_config in data_config.hist_objs_config.items():
                    delta_timestamps.update(
                        {obj_key: [obj_config['step'] * t / dataset_meta.fps for t in range(obj_config['length'])]}
                    )
            dataset = LeRobotDataset(  # dataset loading configuration
                repo_id,
                model_config=model_config,
                delta_timestamps=delta_timestamps,
            )
            if data_config.prompt_from_task:  # if prompt is missing, use task as prompt
                dataset = TransformedDataset(dataset, [_transforms.PromptFromLeRobotTask(dataset_meta.tasks)])
            self._datasets.append(dataset)
        logging.info(f"use multi repos: {repo_ids} with length {len(self)}")

    def __len__(self) -> int:
        return sum(len(dataset) for dataset in self._datasets)

    def __getitem__(self, idx: int) -> dict[str, torch.Tensor]:
        if idx >= len(self):
            raise IndexError(f"Index {idx} out of bounds.")
        # Determine which dataset to get an item from based on the index.
        start_idx = 0
        dataset_idx = 0
        for dataset in self._datasets:
            if idx >= start_idx + dataset._dataset.num_frames:
                start_idx += dataset._dataset.num_frames
                dataset_idx += 1
                continue
            break
        else:
            raise AssertionError("We expect the loop to break out as long as the index is within bounds.")
        
        item = self._datasets[dataset_idx][idx - start_idx]
        item["dataset_index"] = torch.tensor(dataset_idx)

        return item
        

def create_torch_dataset(
    data_config: _config.DataConfig, action_horizon: int, model_config: _model.BaseModelConfig
) -> Dataset:
    """Create a dataset for training."""
    repo_id = data_config.repo_id
    if repo_id is None:
        raise ValueError("Repo ID is not set. Cannot create dataset.")
    if repo_id == "fake":
        return FakeDataset(model_config, num_samples=1024)
    
    dataset = MultiLeRobotDataset(data_config, action_horizon, model_config)
    return dataset


def create_rlds_dataset(
    data_config: _config.DataConfig,
    action_horizon: int,
    batch_size: int,
    *,
    shuffle: bool = False,
) -> Dataset:
    # At the moment, we only support DROID for RLDS datasets.
    return DroidRldsDataset(
        data_dir=data_config.rlds_data_dir,
        batch_size=batch_size,
        shuffle=shuffle,
        action_chunk_size=action_horizon,
        action_space=data_config.action_space,
        filter_dict_path=data_config.filter_dict_path,
    )


def transform_dataset(dataset: Dataset, data_config: _config.DataConfig, *, skip_norm_stats: bool = False) -> Dataset:
    """Transform the dataset by applying the data transforms."""
    norm_stats = {}
    if data_config.repo_id != "fake" and not skip_norm_stats:
        if data_config.norm_stats is None:
            raise ValueError(
                "Normalization stats not found. "
                "Make sure to run `scripts/compute_norm_stats.py --config-name=<your-config>`."
            )
        norm_stats = data_config.norm_stats

    return TransformedDataset(
        dataset,
        [
            *data_config.repack_transforms.inputs,
            *data_config.data_transforms.inputs,
            _transforms.Normalize(norm_stats, use_quantiles=data_config.use_quantile_norm),
            *data_config.model_transforms.inputs,
        ],
    )


